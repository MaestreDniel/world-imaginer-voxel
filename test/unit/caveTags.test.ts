const NEVER = (): boolean => false;
const MiB = 1 << 20;
const ctx = ctxFor('42');
const THRESHOLD = ctx.params.caves.pillars.threshold;
/** The caverns' cave class column of seed 42 (pinned in test/unit/liveness.test.ts). */
const CAVERNS: readonly [number, number] = [546, 25857];

/** The four carving families in the tie order, with their kinds (§3.2). */
const FAMILIES: ReadonlyArray<readonly [tap: string, kind: number]> = [
  ['entrances', CAVE_KIND.entrance], ['cheese', CAVE_KIND.cheese], ['spag3d', CAVE_KIND.spaghetti3d], ['spag2d', CAVE_KIND.spaghetti2d],
];

/** The T stage's density fill of (cx, cz) on `dc` and `tagColumn` after it (with the bounds, else without). */
function tagsOf(dc: DensityContext, cx: number, cz: number, threshold: number, withBounds = true): { solid: Uint8Array; cells: Uint8Array; tags: Uint8Array } {
  const solid = new Uint8Array(98304), cells = new Uint8Array(768), tags = new Uint8Array(98304).fill(13);
  expect(fillDensityColumn(dc.bounds, dc.columns.get(cx, cz), solid, null, null, NEVER, cells)).toBe(true);
  const c = dc.compiled;
  tagColumn(c, caveReadersOf(c), threshold, solid, cells, tags, withBounds ? dc.bounds : null);
  return { solid, cells, tags };
}

/**
 * §3.2's rule at voxel (lx, y, lz) of `dc`'s current column, from `voxelFn` and `tapFn` alone: 0 at y −64 and in solid
 * voxels; pre-cave solidity from `precave`, else `terrain`, else unknown (0); then the lowest candidate, ties in the
 * order E, C, S3, S2, noodle; 9 when none explains the air.
 */
function ruleAt(dc: DensityContext, threshold: number, lx: number, y: number, lz: number): number {
  const c = dc.compiled;
  if (y === -64 || c.voxelFn(lx, y, lz) > 0) return 0;
  const at = (name: string): number | null => (c.tapReader(name) === null ? null : c.tapFn(name, lx, y, lz));
  const pre = at('precave') ?? at('terrain');
  if (pre === null || !(pre > 0)) return 0;
  const present = FAMILIES.map(([name, kind]) => [at(name), kind] as const).filter(([v]) => v !== null) as Array<readonly [number, number]>;
  const p = at('pillars');
  const keep = p === null ? -Infinity : p * 0.0625 < threshold ? -1e6 : p;
  let lowest = Infinity;
  for (const [v] of present) if (v < lowest) lowest = v;
  const caves = Math.max(lowest, keep);
  let best = Infinity, kind: number = CAVE_KIND.other;
  if (caves <= 0) for (const [v, k] of present) if (v < best) { best = v; kind = k; }
  const n = at('noodle');
  if (n !== null && n <= 0 && n < best) kind = CAVE_KIND.noodle;
  return kind;
}

/** A column generated by the T stage on its own store, and its proto view. */
function generate(c: GenContext, cx: number, cz: number) {
  const store = createStore({ shared: false, maxBlockBytes: 8 * MiB, maxByteBytes: 8 * MiB });
  const w = store.claimColumn(cx, cz, 0);
  expect(terrainStage(c, cx, cz, w, NEVER)).toBe(true);
  w.commit(1);
  return store.proto(cx, cz)!;
}

/** Every voxel of (cx, cz) generated by T on `c`: its stored tag equals `ruleAt` on a DensityContext of its own. */
function storedEqualsRule(c: GenContext, cx: number, cz: number): Map<number, number> {
  const view = generate(c, cx, cz);
  const dc = createDensityContext(c);
  dc.column(cx, cz);
  const kinds = new Map<number, number>();
  const threshold = c.params.caves.pillars.threshold;
  for (let y = -64; y < 320; y++) {
    for (let lz = 0; lz < 16; lz++) {
      for (let lx = 0; lx < 16; lx++) {
        const got = view.cave(lx, y, lz);
        const want = ruleAt(dc, threshold, lx, y, lz);
        if (got !== want) throw new Error(`(${cx}, ${cz}) voxel (${lx}, ${y}, ${lz}): stored ${got} ≠ rule ${want}`);
        kinds.set(got, (kinds.get(got) ?? 0) + 1);
      }
    }
  }
  return kinds;
}

/**
 * The default tree's source with the `cheese` and `pillars` taps muted to −1e6 (as `treeMutator` mutes a tap): the caves
 * slot is then −1e6 (keep is −1e6 too), so every cell is decided air before its corners, pre-cave rock included. A
 * muted family alone does not: `keep`'s interval straddles 0 wherever the pillars' noise interval does.
 */
function cheeseMuted(): JsonValue {
  const t = JSON.parse(JSON.stringify(DEFAULT_DENSITY_TREE)) as {
    root: { a: { a: { b: { a: { a: { a: { a: { b: Record<string, unknown> } } } } } } } }; defs: { pillars: Record<string, unknown> };
  };
  const cheese = t.root.a.a.b.a.a.a.a.b;
  if (cheese['op'] !== 'tap' || cheese['name'] !== 'cheese') throw new Error('no cheese tap at root.a.a.b.a.a.a.a.b');
  if (t.defs.pillars['op'] !== 'tap' || t.defs.pillars['name'] !== 'pillars') throw new Error('no pillars tap at defs.pillars');
  cheese['mute'] = -1e6;
  t.defs.pillars['mute'] = -1e6;
  return t as unknown as JsonValue;
}

const num = (v: number): Record<string, unknown> => ({ op: 'const', v });
const y = { op: 'y' };
const noise = (id: string): Record<string, unknown> => ({ op: 'noise', id });
const tapS = (name: string, x: unknown): Record<string, unknown> => ({ op: 'tap', name, x });
const addS = (a: unknown, b: unknown): Record<string, unknown> => ({ op: 'add', a, b });
const mulS = (a: unknown, b: unknown): Record<string, unknown> => ({ op: 'mul', a, b });
const minS = (a: unknown, b: unknown): Record<string, unknown> => ({ op: 'min', a, b });
/** 40 − y: pre-cave rock below y 40. */
const TERRAIN40 = addS(num(40), { op: 'neg', x: y });

describe('the tag on the default tree (SP6a spec §3.2, §10.7)', () => {
  test('64 columns around a cave class column: the tagged set is pre-cave solid ∧ density air voxel for voxel; no tag at y −64; no 9; no cell decided air before its corners holds pre-cave rock; without the bounds the same tags', () => {
    const dc = createDensityContext(ctx);
    const brute = createDensityContext(ctx);
    const kinds = new Map<number, number>();
    let tagged = 0, earlyAir = 0;
    for (let n = 0; n < 64; n++) {
      const cx = CAVERNS[0] - 3 + (n & 7), cz = CAVERNS[1] - 3 + (n >> 3);
      const { solid, cells, tags } = tagsOf(dc, cx, cz, THRESHOLD);
      if (n === 0) expect(tagsOf(createDensityContext(ctx), cx, cz, THRESHOLD, false).tags).toEqual(tags);
      brute.column(cx, cz);
      for (let v = 0; v < 98304; v++) {
        const k = tags[v]!;
        kinds.set(k, (kinds.get(k) ?? 0) + 1);
        if (k !== 0) tagged++;
        if (v < 256) { expect(k, 'y −64 is bedrock').toBe(0); continue; }
        if (solid[v] !== 0) { if (k !== 0) throw new Error(`(${cx}, ${cz}) voxel ${v}: solid, tag ${k}`); continue; }
        const lx = v & 15, lz = (v >> 4) & 15, yy = (v >> 8) - 64;
        const pre = brute.compiled.tapFn('precave', lx, yy, lz);
        if ((k !== 0) !== (pre > 0)) throw new Error(`(${cx}, ${cz}) voxel (${lx}, ${yy}, ${lz}): tag ${k}, precave ${pre}`);
        const cell = (((yy + 64) >> 3) * 4 + (lz >> 2)) * 4 + (lx >> 2);
        if (cells[cell] === 0) {
          earlyAir++;
          if (pre > 0) throw new Error(`(${cx}, ${cz}) voxel (${lx}, ${yy}, ${lz}): decided air before its corners, precave ${pre}`);
        }
      }
    }
    expect(kinds.get(CAVE_KIND.other) ?? 0, 'the default tree yields no 9').toBe(0);
    for (const k of kinds.keys()) expect([0, CAVE_KIND.cheese, CAVE_KIND.spaghetti3d, CAVE_KIND.spaghetti2d, CAVE_KIND.noodle, CAVE_KIND.entrance]).toContain(k);
    expect(kinds.get(CAVE_KIND.cheese) ?? 0).toBeGreaterThan(0);
    expect(tagged).toBeGreaterThan(0);
    expect(earlyAir).toBeGreaterThan(0);
  });

  test('bounds.nodeInterval (the pre-cave check) equals the precave and terrain taps\' intervals after cellInterval, on every cell of a column', () => {
    const dc = createDensityContext(ctx);
    const c = dc.compiled;
    dc.column(...CAVERNS);
    dc.bounds.beginColumn();
    const nodes = ['precave', 'terrain'].map((name) => c.nodes.findIndex((n) => n.op === 'tap' && !n.inside && (n.expr as { name: string }).name === name));
    for (const node of nodes) expect(node).toBeGreaterThanOrEqual(0);
    const a = new Float64Array(2), root = new Float64Array(2);
    for (let cell = 0; cell < 768; cell++) {
      const ci = cell & 3, cj = (cell >> 2) & 3, ck = cell >> 4;
      for (const node of nodes) {
        dc.bounds.nodeInterval(ci, ck, cj, node, a, 0);
        dc.bounds.cellInterval(ci, ck, cj, root, 0);
        expect([a[0], a[1]]).toEqual([dc.bounds.nodeIntervals[2 * node], dc.bounds.nodeIntervals[2 * node + 1]]);
      }
    }
  });

  test('every voxel of the cave class column: tagColumn equals the rule (voxelFn and tapFn)', () => {
    const dc = createDensityContext(ctx);
    const { tags } = tagsOf(dc, ...CAVERNS, THRESHOLD);
    const ref = createDensityContext(ctx);
    ref.column(...CAVERNS);
    for (let v = 0; v < 98304; v++) {
      const want = ruleAt(ref, THRESHOLD, v & 15, (v >> 8) - 64, (v >> 4) & 15);
      if (tags[v] !== want) throw new Error(`voxel ${v}: tag ${tags[v]} ≠ rule ${want}`);
    }
  });
});

describe('the tag on other trees (SP6a spec §3.2: trees without the family taps, D36)', () => {
  test('the cheese and pillars taps muted to −1e6 (cells decided air before their corners where precave > 0): the stored tag equals the per-voxel rule on every voxel', () => {
    const c = ctxFor('42', { density: { defs: cheeseMuted() } });
    const dc = createDensityContext(c);
    const { solid, cells } = tagsOf(dc, ...CAVERNS, THRESHOLD);
    // The branch is exercised: a cell decided air before its corners holds pre-cave rock.
    let early = 0;
    for (let cell = 0; cell < 768 && early === 0; cell++) {
      if (cells[cell] !== 0) continue;
      const ci = cell & 3, cj = (cell >> 2) & 3, ck = cell >> 4;
      if (solid[((8 * ck) * 16 + 4 * cj) * 16 + 4 * ci] !== 0) continue;
      if (dc.compiled.tapFn('precave', 4 * ci, -64 + 8 * ck, 4 * cj) > 0) early++;
    }
    expect(early).toBeGreaterThan(0);
    const kinds = storedEqualsRule(c, ...CAVERNS);
    expect(kinds.get(CAVE_KIND.cheese) ?? 0).toBeGreaterThan(0);
  });

  test('a tree without interpolated (no corners): the stored tag equals the per-voxel rule on every voxel; cheese and noodle both tagged', () => {
    const tree = {
      root: minS(minS(
        tapS('precave', addS(tapS('terrain', TERRAIN40), mulS(noise('detail'), num(4)))),
        tapS('cheese', addS(mulS(noise('cheese'), num(20)), num(6)))),
      tapS('noodle', addS(mulS(noise('noodleToggle'), num(30)), num(10)))),
      defs: {},
    };
    const c = ctxFor('42', { density: { defs: tree as unknown as JsonValue } });
    expect(createDensityContext(c).compiled.interpolatedSlotCount).toBe(0);
    const kinds = storedEqualsRule(c, 0, 0);
    expect(kinds.get(CAVE_KIND.cheese) ?? 0).toBeGreaterThan(0);
    expect(kinds.get(CAVE_KIND.noodle) ?? 0).toBeGreaterThan(0);
    expect(kinds.get(CAVE_KIND.other) ?? 0).toBe(0);
  });

  test('only terrain and noodle taps: density air in pre-cave rock is 4 where the noodle explains it, else 9', () => {
    const tree = {
      root: minS(minS(tapS('terrain', TERRAIN40), tapS('noodle', addS(mulS(noise('noodleToggle'), num(30)), num(10)))),
        addS(mulS(noise('cheese'), num(20)), num(6))),
      defs: {},
    };
    const c = ctxFor('42', { density: { defs: tree as unknown as JsonValue } });
    const dc = createDensityContext(c);
    const { solid, tags } = tagsOf(dc, 0, 0, THRESHOLD);
    const ref = createDensityContext(c);
    ref.column(0, 0);
    const counts = [0, 0];
    for (let v = 256; v < 98304; v++) {
      if (solid[v] !== 0) { expect(tags[v]).toBe(0); continue; }
      const lx = v & 15, lz = (v >> 4) & 15, yy = (v >> 8) - 64;
      if (!(ref.compiled.tapFn('terrain', lx, yy, lz) > 0)) { expect(tags[v]).toBe(0); continue; }
      const want = ref.compiled.tapFn('noodle', lx, yy, lz) <= 0 ? CAVE_KIND.noodle : CAVE_KIND.other;
      if (tags[v] !== want) throw new Error(`voxel (${lx}, ${yy}, ${lz}): tag ${tags[v]} ≠ ${want}`);
      counts[want === CAVE_KIND.noodle ? 0 : 1]++;
    }
    expect(counts[0]).toBeGreaterThan(0);
    expect(counts[1]).toBeGreaterThan(0);
  });

  test('no terrain and no precave tap: density air is 0 (pre-cave solidity unknown; only carver kinds would be tagged)', () => {
    const tree = { root: minS(TERRAIN40, tapS('cheese', addS(mulS(noise('cheese'), num(20)), num(6)))), defs: {} };
    const c = ctxFor('42', { density: { defs: tree as unknown as JsonValue } });
    const { solid, tags } = tagsOf(createDensityContext(c), 0, 0, THRESHOLD);
    let air = 0;
    for (let v = 256; v < 98304; v++) if (solid[v] === 0 && v < 256 * (40 + 64)) air++;
    expect(air).toBeGreaterThan(0);
    expect(tags.every((k) => k === 0)).toBe(true);
  });
});

describe('tagVoxel: ties and pillars (SP6a spec §3.2 step 3)', () => {
  const C = (v: number): Expr => ({ op: 'const', v });
  const tapE = (name: string, x: Expr): Expr => ({ op: 'tap', name, x });
  /**
   * A constant tree shaped as the default root, min(min(precave, caves), noodle) with caves = max(min(E, C, S3, S2),
   * keep) and keep = rangeChoice(P·(1/16), −1e9, threshold, −1e6, P): every tap a constant.
   */
  function fixture(e: number, ch: number, s3: number, s2: number, noodle: number, pillars: number): DensityExpr {
    const fam: Expr = {
      op: 'min', a: { op: 'min', a: { op: 'min', a: tapE('entrances', C(e)), b: tapE('cheese', C(ch)) }, b: tapE('spag3d', C(s3)) }, b: tapE('spag2d', C(s2)),
    };
    const keep: Expr = { op: 'rangeChoice', x: { op: 'mul', a: { op: 'ref', name: 'pillars' }, b: C(0.0625) }, lo: -1e9, hi: THRESHOLD, inside: C(-1e6), outside: { op: 'ref', name: 'pillars' } };
    return {
      root: { op: 'min', a: { op: 'min', a: tapE('precave', C(5)), b: { op: 'max', a: fam, b: keep } }, b: tapE('noodle', C(noodle)) },
      defs: { pillars: tapE('pillars', C(pillars)) },
    };
  }
  const tagOf = (expr: DensityExpr): number => {
    const dc = createDensityContext(ctx, expr);
    dc.column(0, 0);
    const c = dc.compiled;
    expect(c.voxelFn(3, 20, 7), 'density air').toBeLessThanOrEqual(0);
    return tagVoxel(c, caveReadersOf(c), THRESHOLD, 3, 20, 7);
  };

  test.each([
    ['all equal: E (also over the noodle)', [-1, -1, -1, -1, -1, 0], CAVE_KIND.entrance],
    ['C, S3, S2 equal and lowest: C', [-0.5, -1, -1, -1, -0.5, 0], CAVE_KIND.cheese],
    ['S3, S2 equal and lowest: S3', [0, 0, -1, -1, 0, 0], CAVE_KIND.spaghetti3d],
    ['S2 lowest', [0.5, 0.5, 0.5, -1, 0, 0], CAVE_KIND.spaghetti2d],
    ['the noodle lowest', [-1, -1, -1, -1, -2, 0], CAVE_KIND.noodle],
    ['the noodle equal to the lowest family: the family', [-3, -2, -1, -1, -3, 0], CAVE_KIND.entrance],
    ['families closed (caves > 0), the noodle open', [0.5, 0.5, 0.5, 0.5, -0.25, 0], CAVE_KIND.noodle],
    ['pillar rock (keep > 0) opened by the noodle: 4, never a family keep overrides', [-5, -6, -7, -8, -1, 16], CAVE_KIND.noodle],
    ['pillars below the threshold keep nothing: the lowest family', [-5, -6, -7, -8, -1, 0.25], CAVE_KIND.spaghetti2d],
  ] as const)('%s', (_what, v, kind) => {
    expect(tagOf(fixture(v[0], v[1], v[2], v[3], v[4], v[5]))).toBe(kind);
  });

  test('caveReadersOf names the eight taps; a missing tap reads null', () => {
    const dc = createDensityContext(ctx);
    const r = caveReadersOf(dc.compiled);
    for (const k of ['precave', 'terrain', 'entrances', 'cheese', 'spaghetti3d', 'spaghetti2d', 'pillars', 'noodle'] as const) expect(r[k], k).not.toBeNull();
    expect(caveReadersOf(dc.compiled)).toBe(r);
    const bare = createDensityContext(ctx, { root: tapE('noodle', C(-1)), defs: {} });
    const b = caveReadersOf(bare.compiled);
    expect([b.precave, b.terrain, b.entrances, b.cheese, b.spaghetti3d, b.spaghetti2d, b.pillars]).toEqual([null, null, null, null, null, null, null]);
    expect(b.noodle).not.toBeNull();
  });
});

/** How the T stage's fill decides a cell (`fillDensityColumn`'s rule): before its corners, after them (air or solid), or voxel by voxel. */
const EARLY = 0, AIR_AFTER_CORNERS = 1, SOLID_AFTER_CORNERS = 2, STRADDLING = 3;
function cellClasses(dc: DensityContext, cx: number, cz: number): Uint8Array {
  const out = new Uint8Array(768);
  const iv = new Float64Array(2);
  const c = dc.compiled;
  dc.column(cx, cz);
  dc.bounds.beginColumn();
  for (let cell = 0; cell < 768; cell++) {
    const ci = cell & 3, cj = (cell >> 2) & 3, ck = cell >> 4;
    dc.bounds.cellInterval(ci, ck, cj, iv, 0);
    if (iv[1]! < 0 || iv[0]! > 0) { out[cell] = EARLY; continue; }
    c.cellCorners(ci, ck, cj);
    dc.bounds.cellIntervalCorners(ci, ck, cj, iv, 0);
    out[cell] = iv[1]! < 0 ? AIR_AFTER_CORNERS : iv[0]! > 0 ? SOLID_AFTER_CORNERS : STRADDLING;
  }
  return out;
}

/**
 * caveTagAt and solidAt at every voxel of (cx, cz) generated by T on `c` equal the stored tag and solidity (solidAt above
 * y −64); the tagged voxels per cell class.
 */
function probesEqualStored(c: GenContext, cx: number, cz: number): number[] {
  const view = generate(c, cx, cz);
  const dc = createDensityContext(c);
  const classes = cellClasses(createDensityContext(c), cx, cz);
  const tagged = [0, 0, 0, 0];
  for (let y = -64; y < 320; y++) {
    for (let lz = 0; lz < 16; lz++) {
      for (let lx = 0; lx < 16; lx++) {
        const x = 16 * cx + lx, z = 16 * cz + lz;
        const want = view.cave(lx, y, lz);
        const got = caveTagAt(dc, x, y, z);
        if (got !== want) throw new Error(`(${x}, ${y}, ${z}): caveTagAt ${got} ≠ stored ${want}`);
        const solid = view.block(lx, y, lz) !== AIR;
        // y −64 is bedrock in T whatever the density (DT2 never draws it).
        if (y > -64 && solidAt(dc, x, y, z) !== solid) throw new Error(`(${x}, ${y}, ${z}): solidAt ≠ stored solidity ${solid}`);
        if (want !== 0) tagged[classes[(((y + 64) >> 3) * 4 + (lz >> 2)) * 4 + (lx >> 2)]!]!++;
      }
    }
  }
  return tagged;
}

describe('caveTagAt and solidAt (SP6a spec §3.4, D22; Task 12)', () => {
  test('8 columns around the cave class column: caveTagAt equals the stored tag and solidAt the stored solidity on every voxel, tagged voxels in cave interiors (cells decided air after their corners) and in straddling cells', () => {
    const tagged = [0, 0, 0, 0];
    for (let n = 0; n < 8; n++) {
      const t = probesEqualStored(ctx, CAVERNS[0] - 1 + (n & 3), CAVERNS[1] + (n >> 2));
      for (let k = 0; k < 4; k++) tagged[k]! += t[k]!;
    }
    expect(tagged[AIR_AFTER_CORNERS], 'tagged voxels in cells decided air after their corners').toBeGreaterThan(0);
    expect(tagged[STRADDLING], 'tagged voxels in straddling cells').toBeGreaterThan(0);
    expect(tagged[SOLID_AFTER_CORNERS]).toBe(0);
  });

  test('the cheese and pillars taps muted to −1e6: caveTagAt equals the stored tag on every voxel of the cave class column, cells decided air before their corners included', () => {
    const c = ctxFor('42', { density: { defs: cheeseMuted() } });
    const tagged = probesEqualStored(c, ...CAVERNS);
    expect(tagged[EARLY], 'tagged voxels in cells decided air before their corners').toBeGreaterThan(0);
  });

  test('y −64 is 0; solidAt is probe > 0; both refuse what probe refuses (RangeError)', () => {
    const dc = createDensityContext(ctx);
    const [cx, cz] = CAVERNS;
    for (let lx = 0; lx < 16; lx++) expect(caveTagAt(dc, 16 * cx + lx, -64, 16 * cz)).toBe(0);
    for (const y of [-64, -40, 0, 30, 63, 100, 319]) {
      const x = 16 * cx + 5, z = 16 * cz + 9;
      expect(solidAt(dc, x, y, z)).toBe(probe(dc, x, y, z) > 0);
    }
    for (const [x, y, z] of [[0.5, 0, 0], [0, 0.5, 0], [0, 0, 0.5], [0, -65, 0], [0, 320, 0], [524288, 0, 0], [0, 0, -524289], [NaN, 0, 0]] as const) {
      expect(() => caveTagAt(dc, x, y, z), `caveTagAt (${x}, ${y}, ${z})`).toThrow(RangeError);
      expect(() => solidAt(dc, x, y, z), `solidAt (${x}, ${y}, ${z})`).toThrow(RangeError);
    }
  });
});
