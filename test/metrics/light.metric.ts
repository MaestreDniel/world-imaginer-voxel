/**
 * The light's metrics L1, L2, DT1's light part and S1's grass at sky 0 (SP4a spec §9.1, D25, D26; ruling P33), over
 * the regions of `render.metric.ts` (Task 18):
 * - fast: one 6 × 6-column region of seed '42' (profile default) at the spawn (interior 4 × 4);
 * - quick: seeds '42' and '1' × 10 × 10 at each seed's spawn, plus a 10 × 10 region of seed '42' at amplified's and at
 *   floating_islands' golden windows (`sp3eWindow` grown by one ring, so the interior is the window: peaks, overhangs,
 *   the island shadow);
 * - full: eight seeds ('42', '1' … '7') at the spawn, plus the two preset windows.
 * Each region R is generated by `genRegion` upTo 'L' (L on R, D on R + 1, T on R + 2, ruling P31) without the region
 * cache, four times: spiral and shuffled on 1 and on 4 threads (the 4-thread runs in worker directory
 * `lightRegionWorker-<tier>`, ruling P33). The first run's view is measured; the interior columns are R's columns with
 * their 3 × 3 in R (R minus its border ring).
 * - L1 (gated): `mismatches`, the interior voxels whose light byte (sky << 4 | block) differs from `referenceLight`
 *   run over the whole region R (outside R opaque). Light reaches 15 blocks and an interior voxel lies ≥ 16 blocks
 *   inside R, so the box's opaque sides cannot reach it: the reference is exact there. Block light is 0 everywhere
 *   until emitters exist; the block BFS is unit-tested (§9.7).
 * - L2 (gated): `enclosedLit`, the interior air voxels (state air, no fluid) not sky-connected, at least 16 below
 *   `WORLD_SURFACE` (y ≤ WORLD_SURFACE − 16), whose stored sky light is > 0. Sky-connected: reached from the air above
 *   y 319 by a face-connected flood over R through voxels light can enter (effective opacity < 15), crossing faces by
 *   the BFS rule of §4.1 (no face set in `FULL_FACES` of the voxel left or the opposite face of the voxel entered).
 *   An interior voxel with sky > 0 has a sky-15 voxel within 14 steps, so its path to the sky stays inside R: the
 *   flood's opaque sides make no false count. Trivially small before caves (SP6 re-asserts it).
 * - DT1's light part (gated, `.out/DT1.light.json`): `lightMismatches`, the runs of a region whose `litHash` (blocks,
 *   fluid, light, aux A and B of R) differs from the first run's.
 * - S1's `grassSky0` (recorded, activeFrom SP6, `.out/S1.light.json`): the share of grass_block tops (a grass_block
 *   voxel whose voxel above has effective opacity < 15) with sky 0 in the voxel above (above y 319: sky 15), over the
 *   interior columns, pooled; 0 when no region has a grass top. On floating_islands it includes the grass under the
 *   islands (§4.4).
 * Recorded beside the parts, per region (`.<index>` in `sites()` order): L1's mismatches, L2's enclosed air, S1's
 * grass tops and their share at sky 0, and the grass tops under no straight fall (the voxel above below
 * `LIGHT_BLOCKING`) with their lowest sky.
 * The four tests share one measurement (the first to run takes it).
 */
type Tier = 'fast' | 'quick' | 'full';
const TIER = (process.env.METRICS_TIER ?? 'fast') as Tier;
const pick = <T>(fast: T, quick: T, full: T): T => (TIER === 'full' ? full : TIER === 'quick' ? quick : fast);

/** A region of the tier: a seed, a profile and R's rectangle. */
interface Site {
  readonly label: string;
  readonly seed: string;
  readonly profile: ProfileId;
  readonly cx0: number;
  readonly cz0: number;
  readonly size: number;
}

/** `render.metric.ts`' regions (SP4a spec §9.1). */
const SIZE = pick(6, 10, 10);
const SPAWN_SEEDS: readonly string[] = pick(['42'], ['42', '1'], ['42', '1', '2', '3', '4', '5', '6', '7']);
const PRESETS: readonly Sp3ePreset[] = pick([], ['amplified', 'floating_islands'], ['amplified', 'floating_islands']);

function sites(): Site[] {
  const out: Site[] = [];
  for (const seed of SPAWN_SEEDS) {
    const sp = findSpawn(createGenContext(seedFromInput(seed), resolveProfile('default')));
    const half = Math.floor(SIZE / 2);
    out.push({ label: `seed '${seed}' spawn (${sp.x}, ${sp.z})`, seed, profile: 'default', cx0: (sp.x >> 4) - half, cz0: (sp.z >> 4) - half, size: SIZE });
  }
  for (const preset of PRESETS) {
    const w = sp3eWindow(preset);
    out.push({ label: `${preset} window (${w.centreX}, ${w.centreZ})`, seed: '42', profile: preset, cx0: w.chunkX - 1, cz0: w.chunkZ - 1, size: 10 });
  }
  return out;
}

/** DT1's light runs (ruling P33); the first is the reference and the one measured. */
interface Run {
  readonly label: string;
  readonly order: GenRegionOptions['order'];
  readonly threads: GenRegionOptions['threads'];
}

const RUNS: readonly Run[] = [
  { label: 'spiral/1', order: 'spiral', threads: 1 },
  { label: 'shuffled/4', order: 'shuffled', threads: 4 },
  { label: 'spiral/4', order: 'spiral', threads: 4 },
  { label: 'shuffled/1', order: 'shuffled', threads: 1 },
];

/** The six faces as [face, dx, dy, dz, the opposite face]. */
const FACES: ReadonlyArray<readonly [number, number, number, number, number]> = [
  [FACE_NORTH, 0, 0, -1, FACE_SOUTH],
  [FACE_EAST, 1, 0, 0, FACE_WEST],
  [FACE_SOUTH, 0, 0, 1, FACE_NORTH],
  [FACE_WEST, -1, 0, 0, FACE_EAST],
  [FACE_UP, 0, 1, 0, FACE_DOWN],
  [FACE_DOWN, 0, -1, 0, FACE_UP],
];

/**
 * R's final blocks, fluid and light, read section by section, indexed `((y + 64)·H + (z − z0))·W + (x − x0)` for
 * y ∈ [−64, 320), with W = H = 16 · size.
 */
interface Box {
  readonly x0: number;
  readonly z0: number;
  readonly side: number;
  readonly blocks: Uint16Array;
  readonly fluid: Uint8Array;
  readonly light: Uint8Array;
}

function loadBox(view: RegionView): Box {
  const side = 16 * view.w;
  if (view.h !== view.w) throw new Error('light.metric: square regions only');
  const n = side * side * 384;
  const box: Box = { x0: 16 * view.cx0, z0: 16 * view.cz0, side, blocks: new Uint16Array(n), fluid: new Uint8Array(n), light: new Uint8Array(n) };
  for (let cz = view.cz0; cz < view.cz0 + view.h; cz++) {
    for (let cx = view.cx0; cx < view.cx0 + view.w; cx++) {
      const v = view.store.final(cx, cz);
      if (v === null) throw new Error(`light.metric: column (${cx}, ${cz}) has no final set`);
      const bx = 16 * (cx - view.cx0);
      const bz = 16 * (cz - view.cz0);
      for (let sy = 0; sy < 24; sy++) {
        const channels = [[v.sectionBlocks(sy), box.blocks], [v.sectionFluid(sy), box.fluid], [v.sectionLight(sy), box.light]] as const;
        for (const [src, dst] of channels) {
          for (let ly = 0; ly < 16; ly++) {
            for (let lz = 0; lz < 16; lz++) {
              const at = ((16 * sy + ly) * side + bz + lz) * side + bx;
              if (typeof src === 'number') dst.fill(src, at, at + 16);
              else dst.set(src.subarray(ly * 256 + lz * 16, ly * 256 + lz * 16 + 16), at);
            }
          }
        }
      }
    }
  }
  return box;
}

/**
 * The sky-connected voxels of the box (L2): 1 where a face-connected path from the air above y 319 reaches the voxel
 * through voxels of effective opacity < 15, each step allowed by §4.1's face rule. Outside the box's x, z and below
 * y −64 is opaque.
 */
function skyConnected(box: Box): Uint8Array {
  const { side, blocks, fluid } = box;
  const layer = side * side;
  const n = layer * 384;
  const full = DEFAULT_LIGHT_TABLES.fullFaces;
  const seen = new Uint8Array(n);
  const queue = new Int32Array(n);
  let tail = 0;
  const enterable = (v: number): boolean => effOpacity(blocks[v]!, fluid[v]!) < 15;
  // The air above y 319 enters the top layer through its up faces.
  for (let i = 383 * layer; i < n; i++) {
    if (enterable(i) && ((full[blocks[i]!]! >> FACE_UP) & 1) === 0) {
      seen[i] = 1;
      queue[tail++] = i;
    }
  }
  for (let head = 0; head < tail; head++) {
    const u = queue[head]!;
    const x = u % side;
    const z = Math.floor(u / side) % side;
    const y = Math.floor(u / layer);
    const fu = full[blocks[u]!]!;
    for (const [f, dx, dy, dz, opp] of FACES) {
      const vx = x + dx;
      const vy = y + dy;
      const vz = z + dz;
      if (vx < 0 || vx >= side || vz < 0 || vz >= side || vy < 0 || vy >= 384) continue;
      const v = (vy * side + vz) * side + vx;
      if (seen[v] === 1 || ((fu >> f) & 1) !== 0 || ((full[blocks[v]!]! >> opp) & 1) !== 0 || !enterable(v)) continue;
      seen[v] = 1;
      queue[tail++] = v;
    }
  }
  return seen;
}

interface Measurement {
  readonly L1: Record<string, number>;
  readonly L2: Record<string, number>;
  readonly DT1: Record<string, number>;
  readonly S1: Record<string, number>;
  readonly problems: { L1: string[]; L2: string[]; DT1: string[] };
}

async function measure(): Promise<Measurement> {
  const t0 = performance.now();
  const problems = { L1: [] as string[], L2: [] as string[], DT1: [] as string[] };
  let mismatches = 0;
  let skyMismatches = 0;
  let blockMismatches = 0;
  let voxels = 0;
  let enclosed = 0;
  let enclosedLit = 0;
  let lightMismatches = 0;
  let runs = 0;
  let grassTops = 0;
  let grassSky0 = 0;
  const perSiteL1: Record<string, number> = {};
  const perSiteS1: Record<string, number> = {};
  const perSiteL2: Record<string, number> = {};
  const list = sites();
  let columns = 0;
  let genMs = 0;
  for (const [si, s] of list.entries()) {
    let ref = '';
    for (const [i, run] of RUNS.entries()) {
      const r = await genRegion({
        seed: s.seed, params: resolveProfile(s.profile), cx0: s.cx0, cz0: s.cz0, w: s.size, h: s.size, upTo: 'L',
        order: run.order, threads: run.threads, cache: false, workerDir: `lightRegionWorker-${TIER}`,
      });
      runs++;
      genMs += r.timings.totalMs;
      const hash = r.view.litHash();
      if (i > 0) {
        if (hash !== ref) {
          lightMismatches++;
          problems.DT1.push(`${s.label}: ${run.label} litHash ${hash} ≠ ${RUNS[0]!.label} ${ref}`);
        }
        continue;
      }
      ref = hash;
      // The first run: L1, L2 and S1 over the interior columns.
      const view = r.view;
      const box = loadBox(view);
      const { side, blocks, fluid, light } = box;
      const at = (x: number, y: number, z: number): number => ((y + 64) * side + (z - box.z0)) * side + (x - box.x0);
      const reference = referenceLight({ x0: box.x0, z0: box.z0, w: side, h: side }, (x, y, z) => blocks[at(x, y, z)]!, (x, y, z) => fluid[at(x, y, z)]!);
      const connected = skyConnected(box);
      let siteMismatches = 0;
      let siteTops = 0;
      let siteSky0 = 0;
      let siteEnclosed = 0;
      let siteNoFall = 0;
      let siteNoFallMinSky = 15;
      for (let cz = s.cz0 + 1; cz < s.cz0 + s.size - 1; cz++) {
        for (let cx = s.cx0 + 1; cx < s.cx0 + s.size - 1; cx++) {
          columns++;
          const { worldSurface, lightBlocking } = view.aux(cx, cz);
          for (let lz = 0; lz < 16; lz++) {
            for (let lx = 0; lx < 16; lx++) {
              const x = 16 * cx + lx;
              const z = 16 * cz + lz;
              const deepTop = worldSurface[lz * 16 + lx]! - 16;
              const fallFrom = lightBlocking[lz * 16 + lx]!;
              for (let y = -64; y < 320; y++) {
                const k = at(x, y, z);
                const got = light[k]!;
                const want = reference[k]!;
                voxels++;
                if (got !== want) {
                  mismatches++;
                  siteMismatches++;
                  if ((got >> 4) !== (want >> 4)) skyMismatches++;
                  if ((got & 15) !== (want & 15)) blockMismatches++;
                  if (problems.L1.length < 20) problems.L1.push(`${s.label}: (${x}, ${y}, ${z}) light ${got >> 4}/${got & 15} ≠ reference ${want >> 4}/${want & 15} (sky/block)`);
                }
                const state = blocks[k]!;
                if (y <= deepTop && state === AIR && fluid[k] === 0 && connected[k] === 0) {
                  enclosed++;
                  siteEnclosed++;
                  if (got >> 4 > 0) {
                    enclosedLit++;
                    if (problems.L2.length < 20) problems.L2.push(`${s.label}: (${x}, ${y}, ${z}) enclosed air ${deepTop + 16 - y} below WORLD_SURFACE has sky ${got >> 4}`);
                  }
                }
                if (state === GRASS_BLOCK) {
                  const above = y === 319 ? -1 : k + side * side;
                  if (above < 0 || effOpacity(blocks[above]!, fluid[above]!) < 15) {
                    grassTops++;
                    siteTops++;
                    if (above >= 0 && light[above]! >> 4 === 0) {
                      grassSky0++;
                      siteSky0++;
                    }
                    if (y + 1 < fallFrom) {
                      siteNoFall++;
                      siteNoFallMinSky = Math.min(siteNoFallMinSky, light[above]! >> 4);
                    }
                  }
                }
              }
            }
          }
        }
      }
      perSiteL1[`mismatches.${si}`] = siteMismatches;
      perSiteS1[`grassTops.${si}`] = siteTops;
      perSiteS1[`grassSky0.${si}`] = siteTops === 0 ? 0 : siteSky0 / siteTops;
      perSiteS1[`grassNoFall.${si}`] = siteNoFall;
      perSiteS1[`grassNoFallMinSky.${si}`] = siteNoFall === 0 ? 15 : siteNoFallMinSky;
      perSiteL2[`enclosedAir.${si}`] = siteEnclosed;
    }
  }
  const seconds = Math.round(performance.now() - t0) / 1000;
  const common = { regions: list.length, columns, seconds };
  return {
    L1: { mismatches, skyMismatches, blockMismatches, voxels, ...perSiteL1, ...common },
    L2: { enclosedLit, enclosedAir: enclosed, ...perSiteL2, ...common },
    DT1: { lightMismatches, runs, genSeconds: Math.round(genMs) / 1000, ...common },
    S1: { grassSky0: grassTops === 0 ? 0 : grassSky0 / grassTops, grassTopsSky0: grassSky0, grassTops, ...perSiteS1, ...common },
    problems,
  };
}

let measured: Promise<Measurement> | null = null;
const measurement = (): Promise<Measurement> => (measured ??= measure());

metricTest('L1', ['mismatches'], async () => {
  const m = await measurement();
  expect.soft(m.problems.L1, `L1 light mismatches (tier ${TIER}), first 20 of ${m.L1.mismatches}`).toEqual([]);
  return m.L1;
});

metricTest('L2', ['enclosedLit'], async () => {
  const m = await measurement();
  expect.soft(m.problems.L2, `L2 enclosed air with sky light (tier ${TIER}), first 20 of ${m.L2.enclosedLit}`).toEqual([]);
  return m.L2;
});

metricTest('DT1', ['lightMismatches'], async () => {
  const m = await measurement();
  expect.soft(m.problems.DT1, `DT1 light hash mismatches (tier ${TIER})`).toEqual([]);
  return m.DT1;
}, 600_000, { outName: 'DT1.light' });

metricTest('S1', ['grassSky0'], async () => (await measurement()).S1, 600_000, { outName: 'S1.light' });
