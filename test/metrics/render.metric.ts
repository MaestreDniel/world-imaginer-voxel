/**
 * The mesher's metrics R1, R2, R4 and R5 (SP4a spec §9.1, ruling P32), over the interior columns of each tier's
 * regions (R's columns with their four side neighbours in R, which `bruteFaces` needs):
 * - fast: one 6 × 6-column region of seed '42' (profile default) at the spawn (interior 4 × 4);
 * - quick: seeds '42' and '1' × 10 × 10 at each seed's spawn, plus a 10 × 10 region of seed '42' at amplified's and at
 *   floating_islands' golden windows (`sp3eWindow`: the 8 × 8 window grown by one ring, so its interior is the window:
 *   peaks, overhangs, the island shadow);
 * - full: eight seeds ('42', '1' … '7') at the spawn, plus the two preset windows.
 * The spawn region places R's centre (cx0 + ⌊w/2⌋, cz0 + ⌊h/2⌋) on the spawn's column (`findSpawn`).
 * Each region is generated by `genRegion` upTo 'MESH' on 4 threads through the region cache (worker directory
 * `renderRegionWorker-<tier>`, ruling P33), meshed twice: with the Medium preset's options (AO, smooth light; what the
 * page renders) and with `{ao: false, smoothLight: false}` (a cache hit, meshed in process).
 * - R1 (gated): per interior column, category (opaque, water) and meshing, `meshFaceCounts`' unit-face keys merge-walked
 *   against `bruteFaces`' (ruling P32): `hiddenEmitted` counts mesh keys missing from brute plus every repeat after the
 *   first, `visibleMissing` brute keys missing from the mesh; both summed over both meshings.
 * - R2 (gated): opaque quads per visible opaque face (brute's keys), pooled over the interior columns: `quadsPerFaceAo`
 *   on the Medium meshing, `quadsPerFaceNoAo` on the other.
 * - R4 (recorded, activeFrom SP8b): quads per interior column (opaque and water, the Medium meshing), `medianQuads` and
 *   `p95Quads` by nearest rank.
 * - R5 (recorded, activeFrom SP7, D26): `waterQuadsPerFace`, water quads per water unit face (the mesh's keys without
 *   duplicates, ruling P32), pooled, on the Medium meshing; 0 when no region holds water.
 * The four tests share one measurement (the first to run takes it).
 */
type Tier = 'fast' | 'quick' | 'full';
const TIER = (process.env.METRICS_TIER ?? 'fast') as Tier;
const pick = <T>(fast: T, quick: T, full: T): T => (TIER === 'full' ? full : TIER === 'quick' ? quick : fast);

/** A region of the tier: a seed, a profile and R's rectangle. */
interface Site {
  readonly label: string;
  readonly seed: string;
  readonly profile: ProfileId;
  readonly cx0: number;
  readonly cz0: number;
  readonly size: number;
}

const SIZE = pick(6, 10, 10);
const SPAWN_SEEDS: readonly string[] = pick(['42'], ['42', '1'], ['42', '1', '2', '3', '4', '5', '6', '7']);
const PRESETS: readonly Sp3ePreset[] = pick([], ['amplified', 'floating_islands'], ['amplified', 'floating_islands']);

function sites(): Site[] {
  const out: Site[] = [];
  for (const seed of SPAWN_SEEDS) {
    const sp = findSpawn(createGenContext(seedFromInput(seed), resolveProfile('default')));
    const half = Math.floor(SIZE / 2);
    out.push({ label: `seed '${seed}' spawn (${sp.x}, ${sp.z})`, seed, profile: 'default', cx0: (sp.x >> 4) - half, cz0: (sp.z >> 4) - half, size: SIZE });
  }
  for (const preset of PRESETS) {
    const w = sp3eWindow(preset);
    out.push({ label: `${preset} window (${w.centreX}, ${w.centreZ})`, seed: '42', profile: preset, cx0: w.chunkX - 1, cz0: w.chunkZ - 1, size: 10 });
  }
  return out;
}

/** The page's mesher options (`taskHandler.ts`, the Medium preset). */
const MEDIUM_OPTIONS: MeshOptions = { ao: MEDIUM.ao, smoothLight: MEDIUM.smoothLight };
const NO_AO: MeshOptions = { ao: false, smoothLight: false };

/** One R1 comparison: the merge-walk of a sorted mesh key list (duplicates kept) against sorted unique brute keys. */
function faceDiff(mesh: Uint32Array, brute: Uint32Array): { hidden: number; missing: number } {
  let hidden = 0;
  let missing = 0;
  let i = 0;
  let j = 0;
  while (i < mesh.length || j < brute.length) {
    if (j >= brute.length || (i < mesh.length && mesh[i]! < brute[j]!)) {
      hidden++;
      i++;
    } else if (i >= mesh.length || brute[j]! < mesh[i]!) {
      missing++;
      j++;
    } else {
      const k = brute[j]!;
      i++;
      j++;
      while (i < mesh.length && mesh[i] === k) {
        hidden++;
        i++;
      }
    }
  }
  return { hidden, missing };
}

/** The number of distinct values of a sorted array. */
function distinct(a: Uint32Array): number {
  let n = 0;
  for (let i = 0; i < a.length; i++) if (i === 0 || a[i] !== a[i - 1]) n++;
  return n;
}

interface Measurement {
  readonly R1: Record<string, number>;
  readonly R2: Record<string, number>;
  readonly R4: Record<string, number>;
  readonly R5: Record<string, number>;
  readonly problems: string[];
}

async function measure(): Promise<Measurement> {
  const t0 = performance.now();
  const problems: string[] = [];
  const hidden = { ao: 0, noAo: 0 };
  const missing = { ao: 0, noAo: 0 };
  const quadsOpaque = { ao: 0, noAo: 0 };
  let visibleOpaque = 0;
  let visibleWater = 0;
  let quadsWater = 0;
  let waterFaces = 0;
  const perColumn: number[] = [];
  const list = sites();
  let columns = 0;
  let cacheHits = 0;
  for (const s of list) {
    const views: Array<[keyof typeof hidden, RegionView]> = [];
    for (const [variant, meshOptions] of [['ao', MEDIUM_OPTIONS], ['noAo', NO_AO]] as const) {
      const r = await genRegion({
        seed: s.seed, params: resolveProfile(s.profile), cx0: s.cx0, cz0: s.cz0, w: s.size, h: s.size, upTo: 'MESH',
        order: 'spiral', threads: 4, cache: true, workerDir: `renderRegionWorker-${TIER}`, meshOptions,
      });
      if (r.cacheHit) cacheHits++;
      views.push([variant, r.view]);
    }
    for (let cz = s.cz0 + 1; cz < s.cz0 + s.size - 1; cz++) {
      for (let cx = s.cx0 + 1; cx < s.cx0 + s.size - 1; cx++) {
        columns++;
        const brute = bruteFaces(views[0]![1], cx, cz);
        visibleOpaque += brute.opaque.length;
        visibleWater += brute.water.length;
        for (const [variant, view] of views) {
          const p = view.mesh(cx, cz);
          if (p === null) throw new Error(`render.metric: ${s.label}: no mesh for (${cx}, ${cz})`);
          const m = meshFaceCounts(p);
          for (const [cat, mk, bk] of [['opaque', m.opaque, brute.opaque], ['water', m.water, brute.water]] as const) {
            const d = faceDiff(mk, bk);
            hidden[variant] += d.hidden;
            missing[variant] += d.missing;
            if (d.hidden + d.missing > 0) {
              problems.push(`${s.label}, ${variant}, (${cx}, ${cz}) ${cat}: ${d.hidden} hidden emitted, ${d.missing} visible missing`);
            }
          }
          quadsOpaque[variant] += m.quadsOpaque;
          if (variant === 'ao') {
            quadsWater += m.quadsWater;
            waterFaces += distinct(m.water);
            perColumn.push(m.quadsOpaque + m.quadsWater);
          }
        }
      }
    }
  }
  perColumn.sort((a, b) => a - b);
  const ratio = (q: number, f: number): number => (f === 0 ? 0 : q / f);
  const seconds = Math.round(performance.now() - t0) / 1000;
  const common = { regions: list.length, columns, cacheHits, seconds };
  return {
    R1: {
      hiddenEmitted: hidden.ao + hidden.noAo, visibleMissing: missing.ao + missing.noAo,
      hiddenEmittedAo: hidden.ao, hiddenEmittedNoAo: hidden.noAo, visibleMissingAo: missing.ao, visibleMissingNoAo: missing.noAo,
      visibleOpaqueFaces: visibleOpaque, visibleWaterFaces: visibleWater, ...common,
    },
    R2: {
      quadsPerFaceAo: ratio(quadsOpaque.ao, visibleOpaque), quadsPerFaceNoAo: ratio(quadsOpaque.noAo, visibleOpaque),
      quadsOpaqueAo: quadsOpaque.ao, quadsOpaqueNoAo: quadsOpaque.noAo, visibleOpaqueFaces: visibleOpaque, ...common,
    },
    R4: {
      medianQuads: perColumn.length === 0 ? 0 : nearestRank(perColumn, 0.5), p95Quads: perColumn.length === 0 ? 0 : nearestRank(perColumn, 0.95),
      maxQuads: perColumn.length === 0 ? 0 : perColumn[perColumn.length - 1]!, ...common,
    },
    R5: { waterQuadsPerFace: ratio(quadsWater, waterFaces), waterQuads: quadsWater, waterFaces, ...common },
    problems,
  };
}

let measured: Promise<Measurement> | null = null;
const measurement = (): Promise<Measurement> => (measured ??= measure());

metricTest('R1', ['hiddenEmitted', 'visibleMissing'], async () => {
  const m = await measurement();
  expect.soft(m.problems.slice(0, 20), `R1 face mismatches (tier ${TIER}), first 20 of ${m.problems.length}`).toEqual([]);
  return m.R1;
});

metricTest('R2', ['quadsPerFaceAo', 'quadsPerFaceNoAo'], async () => (await measurement()).R2);

metricTest('R4', ['medianQuads', 'p95Quads'], async () => (await measurement()).R4);

metricTest('R5', ['waterQuadsPerFace'], async () => (await measurement()).R5);
